BEGIN;

CREATE TABLE equipment_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    description VARCHAR(500),
    CONSTRAINT equipment_categories_name_not_blank CHECK (btrim(name) <> '')
);

CREATE TABLE locations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    description VARCHAR(500),
    CONSTRAINT locations_name_not_blank CHECK (btrim(name) <> '')
);

CREATE TABLE employees (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(150) NOT NULL,
    department VARCHAR(100) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT employees_full_name_not_blank CHECK (btrim(full_name) <> ''),
    CONSTRAINT employees_department_not_blank CHECK (btrim(department) <> '')
);

CREATE TABLE equipment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inventory_number VARCHAR(50) NOT NULL UNIQUE,
    serial_number VARCHAR(100) NOT NULL UNIQUE,
    category_id BIGINT NOT NULL REFERENCES equipment_categories(id) ON DELETE RESTRICT,
    manufacturer VARCHAR(100) NOT NULL,
    model VARCHAR(100) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'in_stock',
    location_id BIGINT NOT NULL REFERENCES locations(id) ON DELETE RESTRICT,
    purchase_date DATE,
    warranty_until DATE,
    notes VARCHAR(1000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT equipment_inventory_number_not_blank CHECK (btrim(inventory_number) <> ''),
    CONSTRAINT equipment_serial_number_not_blank CHECK (btrim(serial_number) <> ''),
    CONSTRAINT equipment_manufacturer_not_blank CHECK (btrim(manufacturer) <> ''),
    CONSTRAINT equipment_model_not_blank CHECK (btrim(model) <> ''),
    CONSTRAINT equipment_status_valid CHECK (status IN ('in_stock', 'assigned', 'retired'))
);

CREATE TABLE assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id BIGINT NOT NULL REFERENCES equipment(id) ON DELETE RESTRICT,
    employee_id BIGINT NOT NULL REFERENCES employees(id) ON DELETE RESTRICT,
    issued_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    returned_at TIMESTAMPTZ,
    CONSTRAINT assignments_returned_after_issue CHECK (returned_at IS NULL OR returned_at >= issued_at)
);

COMMIT;
